export type Dict = (typeof dict)["en"];

export const LANGS: { code: Lang; label: string; html: string }[] = [
  { code: "zh", label: "中文", html: "zh-CN" },
  { code: "en", label: "English", html: "en" },
  { code: "ja", label: "日本語", html: "ja" },
];

export function getDict(lang: Lang): Dict {
  return dict[lang] as unknown as Dict;
}

export const I18nContext = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void }>({
  lang: "zh",
  t: getDict("zh"),
  setLang: () => {},
});

export const useI18n = () => useContext(I18nContext);

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem("lumen.lang") as Lang | null;
    if (saved && ["zh", "en", "ja"].includes(saved)) return saved;
  } catch {}
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("zh")) return "zh";
  if (nav.startsWith("ja")) return "ja";
  return "en";
}
